/**
 * 微信聊天记录接入（2026-11-16：把原来 wechat-extract-spike 的三步流程沉淀进 dsh）。
 *
 * 用户只需要选择 `xwechat_files` 文件夹；本模块负责：
 *   1. 发现账号目录下的 `db_storage`；
 *   2. 从**运行中的微信进程**读取各库密钥（只读内存，不重启微信、不打断登录态）；
 *   3. 用驱动把加密库转成明文快照，再调 export_msgs.py 导出为每会话 txt；
 *   4. 把 txt 目录交给既有的 `@knowself/chat-ingest` 导入管线。
 *
 * ## 2026-11-17：为什么不再用 Frida 抓密钥
 * 旧实现走 `find_key.py`（Frida spawn 微信 + hook weixin.dll 偏移 `0x35de480`），
 * 两个硬伤：① 必须先退出微信再重新扫码登录，用户「重启完微信后一直没反应」就是卡在
 * 这 300 秒的空等；② hook 偏移写死在 4.1.13.12，微信升到 4.2.0.13 后偏移漂移，
 * 抓到的「候选」根本不是密钥（HMAC 必然失败），脚本仍傻等到超时。
 * 现在改为 `db_keys.py` + `vendor/wechatauto` 的 Config.Cipher 内存扫描：微信保持登录，
 * 只读进程内存，逐个用 page1 HMAC 校验，拿不到就立刻给出可操作的错误。
 *
 * 安全边界：密钥只在内存中传给驱动，不落盘、不打印、不写日志、不通过 REST 返回。
 */
import { spawn } from "node:child_process";
import Database from "better-sqlite3-multiple-ciphers";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * 可区分的失败原因（路由映射为 400 / 409 / 502）。
 *
 * `WECHAT_KEY_CAPTURE_FAILED` 保留在值域里只为兼容老客户端/老日志：2026-11-17 起
 * 不再有「重启微信抓密钥」这条路（改为从运行中的微信进程只读密钥），新代码只会
 * 抛 `WECHAT_KEY_REQUIRED`（可重试：让用户先登录微信）。
 */
export type WechatSourceErrorCode =
  | "WECHAT_PATH_INVALID"
  | "WECHAT_KEY_REQUIRED"
  | "WECHAT_KEY_CAPTURE_FAILED"
  | "WECHAT_EXPORT_FAILED";

export class WechatSourceError extends Error {
  readonly code: WechatSourceErrorCode;
  /** 是否值得原样重试（例如「先去登录微信」再点一次导入）。 */
  readonly recoverable: boolean;

  constructor(code: WechatSourceErrorCode, message: string, recoverable = false) {
    super(message);
    this.name = "WechatSourceError";
    this.code = code;
    this.recoverable = recoverable;
  }
}

/** 一次接入的结果（不含密钥/明文路径以外的敏感信息）。 */
export interface WechatExportResult {
  /** 解压后的 txt 目录（交给 chat-ingest）。 */
  txtDir: string;
  /** 实际使用的账号 db_storage 目录（只用于展示“已找到账号”）。 */
  dbDir: string;
  /**
   * 密钥来源。
   * - `live`：从运行中的微信进程实时读取（2026-11-17 起的唯一路径）；
   * - `reused` / `captured`：旧版缓存/抓取路径，仅保留类型兼容。
   */
  keySource: "live" | "reused" | "captured";
  /** export-all 的结构化摘要。 */
  summary: unknown;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

/** 递归查找 `xwechat_files` 下的账号 db_storage。 */
export function findDbStorage(root: string): { root: string; candidates: string[] } {
  const resolved = resolve(root);
  if (!existsSync(resolved)) {
    throw new WechatSourceError("WECHAT_PATH_INVALID", `路径不存在：${resolved}`);
  }
  if (basename(resolved).toLowerCase() === "db_storage") {
    return { root: dirname(resolved), candidates: [resolved] };
  }
  const candidates: string[] = [];
  let entries: string[] = [];
  try {
    entries = statSync(resolved).isDirectory() ? readDir(resolved) : [];
  } catch {
    entries = [];
  }
  // 允许两种输入：xwechat_files 根，或其下的单个账号目录。
  for (const entry of entries) {
    const child = join(resolved, entry);
    try {
      if (!statSync(child).isDirectory()) continue;
    } catch {
      continue;
    }
    const dbDir = join(child, "db_storage");
    if (existsSync(dbDir)) candidates.push(dbDir);
    // 账号目录自身被选中时
    if (entry === "db_storage" || basename(child) === "db_storage") candidates.push(child);
  }
  const direct = join(resolved, "db_storage");
  if (existsSync(direct) && candidates.length === 0) candidates.push(direct);
  if (candidates.length === 0) {
    throw new WechatSourceError(
      "WECHAT_PATH_INVALID",
      "没有找到微信数据库目录：请选择包含 wxid_* 账号文件夹的 xwechat_files 目录",
    );
  }
  return { root: resolved, candidates: [...new Set(candidates)] };
}

function readDir(path: string): string[] {
  return readdirSync(path);
}

/** 找到插件根目录（开发态 src / 打包态 dist/bundle 都要能找到 scripts/wechat）。 */
function pluginRoot(): string {
  let dir = dirname(fileURLToPath(import.meta.url));
  for (;;) {
    if (existsSync(join(dir, "scripts", "wechat", "find_key.py"))) return dir;
    const parent = dirname(dir);
    if (parent === dir) throw new Error("无法定位 scripts/wechat/find_key.py");
    dir = parent;
  }
}

/** 把内置 Python 脚本复制到可写运行目录（不改写插件包）。 */
function ensureRuntimeTool(runtimeDir: string, dbDir: string): void {
  const sourceDir = join(pluginRoot(), "scripts", "wechat");
  const toolDir = join(runtimeDir, "tool");
  mkdirSync(toolDir, { recursive: true });
  for (const file of ["find_key.py", "decrypt_all.py", "export_msgs.py"]) {
    const src = join(sourceDir, file);
    const dst = join(toolDir, file);
    if (!existsSync(dst) || statSync(dst).size !== statSync(src).size) copyFileSync(src, dst);
  }
  writeFileSync(
    join(toolDir, "local_config.py"),
    `# generated by knowself at runtime; do not commit\nDB_DIR = ${JSON.stringify(dbDir)}\n`,
    "utf8",
  );
}

/**
 * 从**运行中的微信进程**读取各库密钥（`scripts/wechat/db_keys.py`）。
 *
 * 返回 `相对库路径 → 32 字节 hex 页密钥`（如 `message/message_0.db`），
 * 由 `vendor/wechatauto` 扫 Config.Cipher 得到、已逐个通过 page1 HMAC 校验。
 *
 * 失败语义：拿不到任何密钥就立刻抛 `WECHAT_KEY_REQUIRED`（HTTP 409），
 * 文案直接告诉用户「先登录微信」，而不是让前端弹一个必然失败的「重启微信抓密钥」。
 *
 * @param keysDir 密钥缓存目录（`vendor/wechatauto` 用 DPAPI 加密后写这里，
 *   不写 `%LOCALAPPDATA%`；没有 pywin32 时会退回明文，故默认放在 `data/` 下）
 */
async function readDbKeys(dbDir: string, python: string, keysDir: string): Promise<Map<string, string>> {
  let stdout = "";
  let stderr = "";
  try {
    // 密钥扫描是只读内存操作，正常 1~3 秒；60 秒足够覆盖微信进程很大/机器很慢的情况。
    ({ stdout, stderr } = await runProcess(
      python,
      [join(pluginRoot(), "scripts", "wechat", "db_keys.py"), "--db", dbDir, "--json"],
      {
        cwd: join(pluginRoot(), "scripts", "wechat"),
        timeoutMs: 60_000,
        env: { WECHATAUTO_KEYS_DIR: keysDir },
      },
    ));
  } catch (error) {
    throw new WechatSourceError(
      "WECHAT_KEY_REQUIRED",
      `无法从微信进程读取数据库密钥：${error instanceof Error ? error.message : String(error)}。` +
        "请先登录微信并保持窗口打开（不需要退出或重启微信），然后重试。",
      true,
    );
  }
  const marker = "__KNOWSELF_KEYS__";
  let parsed: unknown = null;
  for (const line of stdout.trim().split("\n").reverse()) {
    if (!line.startsWith(marker)) continue;
    try {
      parsed = JSON.parse(line.slice(marker.length).trim()) as unknown;
      break;
    } catch {
      /* keep scanning */
    }
  }
  const keys = new Map<string, string>();
  if (isRecord(parsed) && isRecord(parsed.keys)) {
    for (const [rel, hex] of Object.entries(parsed.keys)) {
      if (typeof hex === "string" && /^[0-9a-fA-F]{64}$/.test(hex)) {
        // Python 的 os.path.relpath 在 Windows 上给的是反斜杠（message\message_0.db），
        // 这里统一成正斜杠，与 materializePlainDbs 的相对路径约定一致。
        keys.set(rel.replace(/\\/g, "/"), hex.toLowerCase());
      }
    }
  }
  if (keys.size === 0) {
    const tail = stderr.trim().split("\n").slice(-4).join("\n");
    throw new WechatSourceError(
      "WECHAT_KEY_REQUIRED",
      "没能读取微信数据库密钥。请确认微信已登录、窗口保持打开，" +
        "并且 dsh 与微信同为 64 位、以相同权限运行（不需要重启微信）后再试。" +
        (tail === "" ? "" : `\n${tail}`),
      true,
    );
  }
  return keys;
}

function runProcess(
  command: string,
  args: string[],
  options: { cwd: string; timeoutMs: number; env?: Record<string, string> },
): Promise<{ stdout: string; stderr: string }> {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, args, {
      cwd: options.cwd,
      windowsHide: true,
      // Windows 控制台默认 GBK：Python 打印 emoji 会话名会 UnicodeEncodeError。
      // 强制子进程 stdout/stderr 用 UTF-8，避免「导出到一半崩掉」。
      env: {
        ...process.env,
        PYTHONIOENCODING: "utf-8",
        PYTHONUTF8: "1",
        ...options.env,
      },
    });
    let stdout = "";
    let stderr = "";
    const timer = setTimeout(() => {
      child.kill();
      reject(new WechatSourceError("WECHAT_EXPORT_FAILED", `命令超时（${Math.round(options.timeoutMs / 1000)} 秒）`));
    }, options.timeoutMs);
    child.stdout.on("data", (chunk: Buffer) => {
      stdout += chunk.toString("utf8");
    });
    child.stderr.on("data", (chunk: Buffer) => {
      stderr += chunk.toString("utf8");
    });
    child.on("error", (error) => {
      clearTimeout(timer);
      reject(new WechatSourceError("WECHAT_EXPORT_FAILED", `无法启动 ${command}：${error.message}`));
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      if (code === 0) resolvePromise({ stdout, stderr });
      else {
        const tail = (stderr || stdout).trim().split("\n").slice(-12).join("\n");
        reject(new WechatSourceError("WECHAT_EXPORT_FAILED", `命令失败（退出码 ${String(code)}）：${tail}`));
      }
    });
  });
}

/**
 * 用驱动把加密库（含 WAL）转成明文库。
 *
 * 为什么不只解主库：4.1.13 把最新消息留在 `message_*.db-wal`；只解 `.db` 会漏掉当天消息
 * （实测 message_1 主库到 2026-07-22，WAL 里有 2026-11-16 的消息）。驱动用
 * `journal_mode=DELETE`（会 checkpoint WAL）再 `rekey=''` 改写成明文，等价于完整快照。
 *
 * 只处理导出需要的库：message_*.db / contact / session。
 * 密钥由 `readDbKeys` 从微信进程内存读来（按库给出 32 字节页密钥），本函数只做
 * 「复制 → 用密钥重写成明文」，不派生、不落盘。
 *
 * @param keys 相对库路径 → 32 字节 hex 页密钥（由 `readDbKeys` 提供）
 */
function materializePlainDbs(
  dbDir: string,
  stagingDir: string,
  keys: Map<string, string>,
): { files: number; warnings: string[] } {
  rmSync(stagingDir, { recursive: true, force: true });
  mkdirSync(stagingDir, { recursive: true });
  const rels: Array<[string, string]> = [];
  const messageDir = join(dbDir, "message");
  if (existsSync(messageDir)) {
    for (const file of readdirSync(messageDir)) {
      if (/^message_\d+\.db$/.test(file)) rels.push([`message/${file}`, `message_${file}`]);
    }
  }
  rels.push(["contact/contact.db", "contact_contact.db"], ["session/session.db", "session_session.db"]);

  const warnings: string[] = [];
  let files = 0;
  for (const [rel, flat] of rels) {
    const src = join(dbDir, rel);
    if (!existsSync(src)) {
      warnings.push(`缺少 ${rel}`);
      continue;
    }
    const keyHex = keys.get(rel);
    if (keyHex === undefined) {
      // 该库没拿到密钥：跳过并告警，不要因为一个冷门库让整次导入失败。
      warnings.push(`缺少 ${rel} 的密钥`);
      continue;
    }
    const dst = join(stagingDir, flat);
    copyFileSync(src, dst);
    for (const suffix of ["-wal", "-shm"]) {
      try {
        copyFileSync(src + suffix, dst + suffix);
      } catch {
        /* 没有 WAL/SHM 是正常情况 */
      }
    }
    const db = new Database(dst);
    try {
      db.pragma("cipher='sqlcipher'");
      db.pragma("legacy=4");
      db.pragma(`key = "x'${keyHex}'"`);
      // 先把 WAL checkpoint 进主库，再解密成明文；两步缺一不可。
      db.pragma("journal_mode = DELETE");
      db.pragma("rekey = ''");
      files += 1;
    } catch (error) {
      throw new WechatSourceError(
        "WECHAT_EXPORT_FAILED",
        `解密 ${flat} 失败：${error instanceof Error ? error.message : String(error)}`,
      );
    } finally {
      db.close();
    }
  }
  return { files, warnings };
}

/**
 * 准备微信聊天记录 txt 导出目录。
 *
 * 流程：发现账号 → 从运行中的微信读密钥 → 解密出明文快照 → export_msgs 导出 txt。
 * **不需要退出/重启微信**。
 *
 * @param options.root 用户选择的 xwechat_files（或账号目录 / db_storage）
 * @param options.dataDir 应用数据目录（导出缓存放这里）
 * @param options.python 覆盖 Python 解释器（默认 `KNOWNSELF_PYTHON`，再退回 `python`）
 */
export async function prepareWechatExport(options: {
  root: string;
  dataDir: string;
  python?: string;
}): Promise<WechatExportResult> {
  const python = options.python ?? process.env.KNOWNSELF_PYTHON?.trim() ?? "python";
  const { candidates } = findDbStorage(options.root);
  // 多账号时选最近使用的一个（db_storage 目录 mtime 最新）。
  const dbDir = candidates
    .slice()
    .sort((a, b) => {
      try {
        return statSync(join(b, "message", "message_0.db")).mtimeMs - statSync(join(a, "message", "message_0.db")).mtimeMs;
      } catch {
        return 0;
      }
    })[0] as string;

  const runtimeDir = join(options.dataDir, "wechat-runtime");
  ensureRuntimeTool(runtimeDir, dbDir);
  const toolDir = join(runtimeDir, "tool");

  const keys = await readDbKeys(dbDir, python, join(runtimeDir, "keys"));

  const outDir = join(options.dataDir, "wechat-export", "current");
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  const stagingDir = join(options.dataDir, "wechat-export", ".staging");
  const materialized = materializePlainDbs(dbDir, stagingDir, keys);
  if (materialized.files === 0) {
    // 带上具体告警（缺哪个库 / 缺哪个库的密钥），否则只剩一句「均缺失」无法排查
    const detail = materialized.warnings.slice(0, 4).join("；");
    throw new WechatSourceError(
      "WECHAT_EXPORT_FAILED",
      `没有可解密的微信数据库（message/contact/session 均缺失）${detail === "" ? "" : `：${detail}`}`,
    );
  }
  const exportScript = join(pluginRoot(), "scripts", "wechat", "export-all.mjs");
  const { stdout } = await runProcess(
    process.execPath,
    [
      exportScript,
      "--tool",
      toolDir,
      "--db",
      stagingDir,
      "--decrypted",
      stagingDir,
      "--out",
      outDir,
      "--python",
      python,
      "--skip-decrypt",
      "--json",
    ],
    { cwd: toolDir, timeoutMs: 600_000 },
  );
  let summary: unknown = null;
  for (const line of stdout.trim().split("\n").reverse()) {
    try {
      summary = JSON.parse(line) as unknown;
      break;
    } catch {
      /* keep scanning */
    }
  }
  // 导出成功后删掉明文 staging 库，减少聊天原文在磁盘上的副本；失败时保留以便排错。
  rmSync(stagingDir, { recursive: true, force: true });
  return { txtDir: outDir, dbDir, keySource: "live", summary };
}
